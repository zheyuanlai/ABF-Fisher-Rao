#!/usr/bin/env python
"""Small REAL fixture tree for the Experiment A analysis tools (synthetic: never production evidence).

    python scripts/final_campaign/expA_make_fixtures.py --root DIR [--cells-dir configs/final_campaign/cells/expA]
        [--Ns 16 4] [--n-steps 16000] [--seeds 10] [--workers 8] [--ramp-t 0.02] [--window-t 0.1] [--force]
        [--dry-run]

Every Experiment A cell config (configs/final_campaign/cells/expA/*.json, read only) is reduced to a fixture cell the
way scripts/mechanism/make_cell_fixtures.py reduces the mechanism cells: N ladder --Ns, budget B = Ns[0] x --n-steps
walker-steps (n_steps = B / N a multiple of 200 at every N), the first --seeds production seed labels, every location
under --root (configs/cells/expA/<cell>.json, results/expA/<cell>/N<N>/s<seed>_<method>.npz, results/expA/ledger.csv
in scripts/mechanism/run_cells.py's columns, analysis/expA/<cell>, figures/expA/<cell>, references/), and
'_fixture_of' = the production cell config.  So that FR acts and the genealogy window closes within the tiny horizon,
two engine knobs are overridden in the FIXTURE ONLY (recorded in '_fixture_overrides'): ramp_t (default 0.02 t.u.)
and genealogy_window_t (default 0.1 t.u.).  h, the model (lambda), every other knob, the thresholds and the grid
rules are the production cell's.  Runs are made by the REAL engine src/gateway_family_numba.run_job (default save
grid prereg_save_grid, diagnostics D1-D4 on); the references by scripts/mechanism/build_references.py (imported by
path, unchanged) with --cells-root <root>/configs/cells.

Resumable: a complete run whose signature matches is skipped (gateway_family_numba.run_job); --force deletes this
fixture's run files first.  Writes nothing outside --root, which must not be inside results/, figures/ or configs/.
CPU only, single-threaded numba per job, at most --workers jobs at once (pin the process with taskset).
"""
from __future__ import annotations

import argparse
import copy
import csv
import importlib.util
import json
import os
import sys
import time

os.environ["CUDA_VISIBLE_DEVICES"] = ""
for _k in ("NUMBA_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ[_k] = "1"

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import expA_analysis_common as C  # noqa: E402

LEDGER_FIELDS = ["experiment", "variant", "N", "seed", "method", "n_steps", "status", "wall_s", "peak_rss_mb",
                 "n_force_evals", "finished_utc", "note"]
DEFAULT_NS = (16, 4)
DEFAULT_N_STEPS = 16000
DEFAULT_SEEDS = 10


def fixture_cell(P, cfg_path, root, Ns, n_steps0, n_seeds, ramp_t, window_t):
    """A production Experiment A cell config reduced to a fixture located under ``root``."""
    F = copy.deepcopy(P)
    name, exp = P["cell"], P["experiment"]
    h = float(P["engine_cfg"]["h"])
    B = int(Ns[0]) * int(n_steps0)
    for N in Ns:
        if B % N or (B // N) % 200:
            raise C.ExpAError(f"fixture B {B} / N {N} is not an integer multiple of 200 steps")
    F["_frozen"] = (f"FIXTURE (not a production config): {C.rel(cfg_path)} with reduced B, N ladder and seeds and two "
                    "overridden engine knobs; generated by scripts/final_campaign/expA_make_fixtures.py")
    F["_fixture_of"] = C.rel(cfg_path)
    F["_fixture_overrides"] = dict(ramp_t=float(ramp_t), genealogy_window_t=float(window_t),
                                   production_ramp_t=P["engine_cfg"].get("ramp_t"),
                                   production_genealogy_window_t=P["engine_cfg"].get("genealogy_window_t"))
    F["engine_cfg"] = dict(P["engine_cfg"], ramp_t=float(ramp_t), genealogy_window_t=float(window_t))
    F["B"] = B
    F["N_ladder"] = [int(n) for n in Ns]
    F["N_coarse"] = [int(n) for n in Ns]
    F["seeds"] = [int(s) for s in P["seeds"][:n_seeds]]
    F["anchor"] = dict(N0=int(max(Ns)), T0=(B // int(max(Ns))) * h)
    F["T_N"] = {str(N): (B // N) * h for N in Ns}
    rd = os.path.join(root, "results", exp, name)
    F["results_dir"] = rd
    F["out_dir"] = os.path.basename(rd)
    F["analysis_dir"] = os.path.join(root, "analysis", exp, name)
    F["fig_dir"] = os.path.join(root, "figures", exp, name)
    F["reference_file"] = os.path.join(root, "references", os.path.basename(P["reference_file"]))
    F["ledger"] = os.path.join(root, "results", exp, "ledger.csv")
    F["ledger_filter"] = dict(experiment=exp, variant=name)
    return F


def run_one(args):
    cfg, N, seed, method, n_steps, path, exp, variant = args
    import gateway_family_numba as E
    t0 = time.time()
    status, rec = "complete", {}
    try:
        res = E.run_job(cfg, method, N, seed, n_steps, path, checkpoint_every_s=600.0)
        rec = dict(wall_s=float(res.get("wall_s", time.time() - t0)), peak_rss_mb=float(res.get("peak_rss_mb", "nan")),
                   n_force_evals=int(res.get("n_force_evals", -1)))
    except Exception as e:  # noqa: BLE001
        status = f"FAILED: {type(e).__name__}: {e}"
        rec = dict(wall_s=time.time() - t0, peak_rss_mb=float("nan"), n_force_evals=-1)
    return dict(experiment=exp, variant=variant, N=N, seed=seed, method=method, n_steps=n_steps, status=status,
                finished_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), note="fixture", **rec)


def build_references(root):
    spec = importlib.util.spec_from_file_location(
        "mech_build_references", os.path.join(C.ROOT, "scripts", "mechanism", "build_references.py"))
    BR = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(BR)
    return BR.main(["--cells-root", os.path.join(root, "configs", "cells")])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True)
    ap.add_argument("--cells-dir", default=C.CELLS_DIR, help="production cell configs to reduce (read only)")
    ap.add_argument("--Ns", type=int, nargs="+", default=list(DEFAULT_NS))
    ap.add_argument("--n-steps", type=int, default=DEFAULT_N_STEPS, help="n_steps at the first N of --Ns")
    ap.add_argument("--seeds", type=int, default=DEFAULT_SEEDS)
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--ramp-t", type=float, default=0.02)
    ap.add_argument("--window-t", type=float, default=0.1)
    ap.add_argument("--lams", type=float, nargs="*", default=None, help="only these lambdas")
    ap.add_argument("--force", action="store_true", help="delete this fixture's run files first")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    for d in (os.path.join(C.ROOT, "results"), os.path.join(C.ROOT, "figures"), os.path.join(C.ROOT, "configs")):
        if root == d or root.startswith(d + os.sep):
            raise C.ExpAError(f"fixture root {root} is inside {d}")
    prod = C.load_cells(a.cells_dir)
    if not prod:
        raise C.ExpAError(f"no cell config under {a.cells_dir}")
    jobs, cells = [], []
    for lam, rec in sorted(prod.items()):
        if a.lams and lam not in a.lams:
            continue
        F = fixture_cell(rec["P"], rec["config"], root, a.Ns, a.n_steps, a.seeds, a.ramp_t, a.window_t)
        p = os.path.join(root, "configs", "cells", F["experiment"], f"{F['cell']}.json")
        cells.append((p, F))
        for N in F["N_ladder"]:
            for s in F["seeds"]:
                for m in ("abf", "fr"):
                    path = os.path.join(F["results_dir"], f"N{N}", f"s{s}_{m}.npz")
                    jobs.append((F["engine_cfg"], int(N), int(s), m, F["B"] // int(N), path, F["experiment"],
                                 F["cell"]))
    print(f"{len(cells)} fixture cells, {len(jobs)} runs (B {cells[0][1]['B']:,}, N {a.Ns}, {a.seeds} seeds) -> {root}",
          flush=True)
    if a.dry_run:
        for p, F in cells:
            print(f"  {p}: lambda {F['model']['lam']:g}, T_N {F['T_N']}")
        return 0
    for p, F in cells:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as fh:
            json.dump(F, fh, indent=1)
    if a.force:
        for j in jobs:
            for q in (j[5], j[5] + ".ckpt.npz"):
                if os.path.exists(q):
                    os.remove(q)
    import gateway_family_numba as E
    E.run_arm(dict(h=2.5e-5, variant="shift", kappa=1.0, lam=4.0), "fr", 4, 1, 200, [200])   # warm the numba cache
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    with ProcessPoolExecutor(max_workers=a.workers) as ex:
        rows = list(ex.map(run_one, jobs, chunksize=4))
    failed = [r for r in rows if r["status"] != "complete"]
    by_ledger = {}
    for (p, F) in cells:
        by_ledger.setdefault(F["ledger"], [])
    for r in rows:
        F = next(F for _, F in cells if F["cell"] == r["variant"])
        by_ledger[F["ledger"]].append(r)
    for lp, rws in by_ledger.items():
        os.makedirs(os.path.dirname(lp), exist_ok=True)
        with open(lp, "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=LEDGER_FIELDS)
            w.writeheader()
            for r in rws:
                w.writerow({k: r.get(k) for k in LEDGER_FIELDS})
    print(f"{len(rows)} runs in {time.time() - t0:.1f} s; {len(failed)} failed {[f['status'] for f in failed[:3]]}",
          flush=True)
    rc = build_references(root)
    return 1 if (failed or rc) else 0


if __name__ == "__main__":
    sys.exit(main())
