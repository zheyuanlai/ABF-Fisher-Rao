#!/usr/bin/env python
"""Small but REAL fixture tree for the mechanism-cell analysis path (scripts/equal_budget/{analyze_ladder,
plot_config,plot_synthesis,audit_completeness}.py --system gateway_family; scripts/mechanism/cross_cell.py).

    python scripts/mechanism/make_cell_fixtures.py [--root DIR] [--cells EXP/VARIANT ...] [--workers 8] [--force]

Every production cell config (configs/mechanism/cells/, scripts/mechanism/make_cell_configs.py) is reduced the way
scripts/equal_budget/make_fixtures.py reduces the equal-budget ladders -- budget B = 8 x 2e6 walker-steps, N ladder
{8, 2} (T_N = 50, 200 at h 2.5e-5), seeds 8100-8102; h, every engine knob, the model fields, thresholds and the save
grid rule (run_ladder.save_grid: 200 uniform + 24 log u + physical checkpoints) unchanged -- and its runs are made by
the REAL engines:
  reuse cells (alpha1, lam1: engine_version gateway_ladder_numba/2)  src/gateway_ladder_numba.run_job with the
      equal-budget gateway production engine_cfg (no model fields), into ONE shared tree <root>/results/eqb_gateway
      (both cells read it, as production does);
  every other cell (gateway_family_numba/1)  src/gateway_family_numba.run_job with the cell's engine_cfg, into
      <root>/results/mechanism/<experiment>/<variant>.
Writes <root>/configs/cells/<experiment>/<variant>.json (fixture configs: absolute results_dir / analysis_dir /
fig_dir / reference_file / ledger under <root>, '_fixture_of' = the production cell config), the ledgers in the
PRODUCTION layout (new-engine cells: ONE <root>/results/mechanism/<experiment>/ledger.csv per experiment with
scripts/mechanism/run_cells.py's columns experiment, variant, ...; the reuse tree: run_ladder's <root>/results/
eqb_gateway/ledger.csv), the reuse-gate record of the reuse cells (scripts/mechanism/reuse_gate.py on the fixture
files: gateway_family_numba at alpha 1, lam 1 vs the gateway_ladder_numba fixture files, every fixture N, both arms;
<root>/reuse_gate/reuse_gate.json) and the frozen references (scripts/mechanism/build_references.py --cells-root
<root>/configs/cells) into <root>/references.  Default root: the session scratchpad (MECH_FIXTURE_ROOT overrides).
CPU only, numba single threaded per job, at most --workers parallel jobs.  FIXTURE DATA: tiny budgets, never
production evidence.
"""
